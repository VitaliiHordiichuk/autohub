-- 130: durable cleanup queue for superseded Mercedes TXT uploads.
-- The old file is NEVER deleted inside the activation transaction.
-- This trigger only records intent; a separately gated worker performs cleanup.
BEGIN;

CREATE TABLE public.special_order_txt_cleanup_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_key VARCHAR(80) NOT NULL
    CHECK (source_key = 'mercedes-txt'),
  old_import_id BIGINT NOT NULL
    REFERENCES public.special_order_import_runs(id),
  activated_import_id BIGINT NOT NULL
    REFERENCES public.special_order_import_runs(id),
  old_upload_file_id UUID NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'RETRY', 'DONE', 'SKIPPED')),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_error_code VARCHAR(96),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  CONSTRAINT special_order_txt_cleanup_jobs_revision_check
    CHECK (old_import_id <> activated_import_id),
  CONSTRAINT special_order_txt_cleanup_jobs_unique
    UNIQUE (source_key, old_import_id, activated_import_id)
);

CREATE INDEX special_order_txt_cleanup_jobs_pending_idx
  ON public.special_order_txt_cleanup_jobs (next_attempt_at, id)
  WHERE status IN ('PENDING', 'RETRY');

-- A stored job becomes visible only if the active-revision change commits.
-- A failed or rolled-back activation cannot enqueue file deletion.
CREATE FUNCTION public.maka_enqueue_superseded_mercedes_txt_v1()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
AS $fn$
BEGIN
  IF OLD.source_key = 'mercedes-txt'
     AND NEW.source_key = OLD.source_key
     AND OLD.active_import_id IS NOT NULL
     AND NEW.active_import_id IS NOT NULL
     AND OLD.active_import_id IS DISTINCT FROM NEW.active_import_id
  THEN
    INSERT INTO public.special_order_txt_cleanup_jobs
      (source_key, old_import_id, activated_import_id, old_upload_file_id)
    SELECT OLD.source_key, r.id, NEW.active_import_id, r.upload_file_id
    FROM public.special_order_import_runs AS r
    WHERE r.id = OLD.active_import_id
      AND r.source_key = OLD.source_key
      AND r.upload_file_id IS NOT NULL
    ON CONFLICT (source_key, old_import_id, activated_import_id)
    DO NOTHING;
  END IF;

  RETURN NEW;
END;
$fn$;

CREATE TRIGGER maka_queue_superseded_mercedes_txt_v1
AFTER UPDATE OF active_import_id
ON public.special_order_sources
FOR EACH ROW
WHEN (OLD.active_import_id IS DISTINCT FROM NEW.active_import_id)
EXECUTE FUNCTION public.maka_enqueue_superseded_mercedes_txt_v1();

-- The application account needs to enqueue jobs when it activates a revision.
-- The cleanup worker also needs to read and update its own queue.
GRANT SELECT, INSERT, UPDATE
  ON public.special_order_txt_cleanup_jobs TO autohub_app;
GRANT USAGE, SELECT
  ON SEQUENCE public.special_order_txt_cleanup_jobs_id_seq TO autohub_app;

COMMIT;
